type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (key: string, params?: Record<string, string | number>) => string; tCat: (cat: string, language?: Lang) => string; tArea: (area: string) => string };

const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<Lang>(() => {
    const saved = typeof window !== 'undefined' ? localStorage.getItem('byc-lang') : null;
    return saved === 'el' || saved === 'en' ? saved : 'en';
  });

  useEffect(() => {
    localStorage.setItem('byc-lang', lang);
  }, [lang]);

  const t = useCallback((key: string, params?: Record<string, string | number>) => {
    let str = dict[key]?.[lang] ?? key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(new RegExp(`{${k}}`, 'g'), String(v));
      }
    }
    return str;
  }, [lang]);
  const tCat = (cat: string, language: Lang = lang) => {
    const key = cat.trim().toLowerCase().replace(/[_-]+/g, ' ');
    return Object.entries(dict).find(([entry]) => entry.toLowerCase() === 'cat.' + key)?.[1][language] ?? cat;
  };
  const tArea = (area: string) => dict[`area.${area}`]?.[lang] ?? area;

  return (
    <I18nContext.Provider value={{ lang, setLang, t, tCat, tArea }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
